-- Find the user who has ordered the highest total quantity.
WITH FILTRD AS (
SELECT
    U.NAME AS USER_NAME,
    COUNT(O.PRODUCT_ID) AS COUNT_OF_ORDS
FROM
	USERS U LEFT JOIN ORDERS O 
    ON U.USER_ID = O.USER_ID
    JOIN PRODUCTS P ON 
    P.PRODUCT_ID = O.PRODUCT_ID
    GROUP BY U.NAME
), CNT AS(
SELECT 
	USER_NAME,
    COUNT_OF_ORDS,
	RANK() OVER(ORDER BY COUNT_OF_ORDS DESC) AS RNK
FROM
	FILTRD)
SELECT
	USER_NAME 
FROM 
	CNT WHERE RNK =1;


-- Find the category with the highest total revenue.
WITH FILTRD AS (
SELECT 
	P.CATEGORY,
    SUM(P.PRICE * O.QUANTITY) AS SM
FROM 
	PRODUCTS P JOIN ORDERS O ON 
    P.PRODUCT_ID = O.PRODUCT_ID
    GROUP BY 
		P.CATEGORY)
SELECT * FROM FILTRD ORDER BY SM DESC LIMIT 1;
