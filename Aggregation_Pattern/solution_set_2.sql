-- Find the total revenue generated overall.
WITH JOINED AS (
SELECT 
	P.PRODUCT_ID,
    SUM(P.PRICE * O.QUANTITY) AS TOTAL_REVENUE_PER_PRODUCT
FROM
	PRODUCTS P JOIN ORDERS O ON P.PRODUCT_ID = O.PRODUCT_ID
    GROUP BY P.PRODUCT_ID)
SELECT 
	SUM(TOTAL_REVENUE_PER_PRODUCT) AS REVENUE_OVERALL FROM JOINED;
    
