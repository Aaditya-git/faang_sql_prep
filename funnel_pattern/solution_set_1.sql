-- Count how many users moved from view_product → add_to_cart in the correct order.
WITH MIN_TIME AS(
SELECT
	USER_ID,
    MIN(EVENT_TIME) AS MIN_EVT_TM_VWP
FROM
	EVENTS
    WHERE EVENT_NAME = LOWER('VIEW_PRODUCT')
	GROUP BY USER_ID
)
SELECT
	COUNT(DISTINCT M.USER_ID) AS CT_OF_CORRECT_ORDERS
FROM
	MIN_TIME M  
    JOIN EVENTS E ON
		M.USER_ID = E.USER_ID
        AND E.EVENT_NAME = LOWER('ADD_TO_CART')
	WHERE E.EVENT_TIME > MIN_EVT_TM_VWP;


