-- a) Basic
-- Count how many users performed each event (view_product, add_to_cart, purchase).
WITH COLM AS (
SELECT
	USER_ID,
    MIN(CASE WHEN EVENT_NAME = 'view_product' THEN 1  END) AS VP,
    MIN(CASE WHEN EVENT_NAME = 'add_to_cart' THEN 1  END) AS AC,
    MIN(CASE WHEN EVENT_NAME = 'purchase' THEN 1  END) AS P
FROM
	EVENTS
    GROUP BY USER_ID)
SELECT 
	COUNT(VP) AS CT1,
    COUNT(AC) AS CT2,
    COUNT(P) AS CT3
FROM 
	COLM ;
-- Count how many users performed at least one purchase.          
WITH CT AS (        
SELECT 
	USER_ID,
    SUM(CASE WHEN EVENT_NAME = LOWER('VIEW_PRODUCT') THEN 1 ELSE 0 END) AS VP_CT,
    SUM(CASE WHEN EVENT_NAME = LOWER('ADD_TO_CART') THEN 1 ELSE 0 END) AS AC_CT,
    SUM(CASE WHEN EVENT_NAME = LOWER('PURCHASE') THEN 1 ELSE 0 END) AS P_CT
FROM
	EVENTS
    GROUP BY USER_ID)
SELECT 
	*
FROM CT WHERE P_CT >=1;


